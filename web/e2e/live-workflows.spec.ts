  async function signIn(page:Page,username:string,password:string) {
    await page.goto('/')
    await page.getByLabel('用户名',{exact:true}).fill(username)
    await page.getByLabel('密码',{exact:true}).fill(password)
    await page.getByRole('button',{name:'登录',exact:true}).click()
    await expect(page.locator('.sidebar')).toBeVisible()
  }
  function monitor(page:Page) {
    const failures:string[]=[]
    page.on('pageerror',error=>failures.push('JS: '+error.message))
    page.on('console',entry=>{if(entry.type()==='error')failures.push('console: '+entry.text())})
    page.on('response',response=>{if(response.url().includes('/api/')&&response.status()>=400)failures.push(response.status()+' '+response.url())})
    return failures
  }
  async function loaded(page:Page) {
    await page.waitForLoadState('networkidle')
    await expect(page.locator('.loading')).toHaveCount(0)
    await expect(page.locator('.notice.error')).toHaveCount(0)
  }
  async function tabs(page:Page) {
    const labels=await page.locator('.tabs button').allTextContents()
    for(const text of labels) {await page.locator('.tabs').getByRole('button',{name:text,exact:true}).click();await loaded(page)}
  }

